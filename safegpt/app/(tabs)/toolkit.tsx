function genId() { return Date.now().toString(36) + Math.random().toString(36).slice(2); }

function buildFieldBlock(f: Record<string, string>): string {
  const lines = Object.entries(f)
    .filter(([, v]) => v && v.trim())
    .map(([k, v]) => `${k}: ${v}`);
  return lines.length > 0 ? `Available Information:\n${lines.join("\n")}\n` : "";
}

